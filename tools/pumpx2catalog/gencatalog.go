//go:build ignore

// gencatalog turns CatalogDump's JSON (stdin) into the Go source of
// pkg/pumpx2/messages/catalog_gen.go (stdout).
// Run it through regen.sh, which builds and runs the dumper against a cliparser jar.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
)

type dump struct {
	Characteristics []struct {
		Name string `json:"name"`
		UUID string `json:"uuid"`
	} `json:"characteristics"`
	Messages []struct {
		Name     string `json:"name"`
		Request  string `json:"request"`
		Response string `json:"response"`
	} `json:"messages"`
	Opcodes []struct {
		Characteristic string `json:"characteristic"`
		Opcode         int    `json:"opcode"`
		Class          string `json:"class"`
	} `json:"opcodes"`
	Classes []struct {
		Name       string `json:"name"`
		SimpleName string `json:"simpleName"`
		Props      struct {
			OpCode                  int    `json:"opCode"`
			Size                    int    `json:"size"`
			VariableSize            bool   `json:"variableSize"`
			Stream                  bool   `json:"stream"`
			Signed                  bool   `json:"signed"`
			Type                    string `json:"type"`
			Characteristic          string `json:"characteristic"`
			ModifiesInsulinDelivery bool   `json:"modifiesInsulinDelivery"`
			MinAPI                  string `json:"minApi"`
			SupportedDevices        string `json:"supportedDevices"`
			Response                string `json:"response"`
			Request                 string `json:"request"`
		} `json:"props"`
		Fields []struct {
			Name       string `json:"name"`
			Type       string `json:"type"`
			DeclaredIn string `json:"declaredIn"`
		} `json:"fields"`
		Constructors []struct {
			Params []struct {
				Name string `json:"name"`
				Type string `json:"type"`
			} `json:"params"`
		} `json:"constructors"`
		EmptyToString      string `json:"emptyToString"`
		EmptyToStringError string `json:"emptyToStringError"`
	} `json:"classes"`
}

func main() {
	raw, err := io.ReadAll(os.Stdin)
	if err != nil {
		log.Fatal(err)
	}
	var d dump
	if err := json.Unmarshal(raw, &d); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/pumpx2catalog/regen.sh from the pumpX2 cliparser jar; DO NOT EDIT.\n\n")
	b.WriteString("package messages\n\n")

	b.WriteString("var catalogCharacteristics = []characteristicInfo{\n")
	for _, c := range d.Characteristics {
		fmt.Fprintf(&b, "\t{Name: %q, UUID: %q},\n", c.Name, c.UUID)
	}
	b.WriteString("}\n\n")

	b.WriteString("var catalogMessages = []enumEntry{\n")
	for _, m := range d.Messages {
		fmt.Fprintf(&b, "\t{Name: %q, Request: %q, Response: %q},\n", m.Name, m.Request, m.Response)
	}
	b.WriteString("}\n\n")

	b.WriteString("var catalogOpcodes = []opcodeEntry{\n")
	for _, o := range d.Opcodes {
		fmt.Fprintf(&b, "\t{Characteristic: %q, Opcode: %d, Class: %q},\n", o.Characteristic, o.Opcode, o.Class)
	}
	b.WriteString("}\n\n")

	b.WriteString("var catalogClasses = []*Class{\n")
	for _, c := range d.Classes {
		p := c.Props
		fmt.Fprintf(&b, "\t{\n\t\tName: %q,\n\t\tSimpleName: %q,\n", c.Name, c.SimpleName)
		fmt.Fprintf(&b, "\t\tProps: Props{OpCode: %d, Size: %d, VariableSize: %t, Stream: %t, Signed: %t, Type: %q, Characteristic: %q, ModifiesInsulinDelivery: %t, MinAPI: %q, SupportedDevices: %q, Response: %q, Request: %q},\n",
			p.OpCode, p.Size, p.VariableSize, p.Stream, p.Signed, p.Type, p.Characteristic, p.ModifiesInsulinDelivery, p.MinAPI, p.SupportedDevices, p.Response, p.Request)
		b.WriteString("\t\tFields: []Field{\n")
		for _, f := range c.Fields {
			fmt.Fprintf(&b, "\t\t\t{Name: %q, Type: %q, DeclaredIn: %q},\n", f.Name, f.Type, f.DeclaredIn)
		}
		b.WriteString("\t\t},\n\t\tConstructors: []Constructor{\n")
		for _, ctor := range c.Constructors {
			b.WriteString("\t\t\t{Params: []Param{")
			for i, prm := range ctor.Params {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "{Name: %q, Type: %q}", prm.Name, prm.Type)
			}
			b.WriteString("}},\n")
		}
		b.WriteString("\t\t},\n")
		if c.EmptyToStringError != "" {
			fmt.Fprintf(&b, "\t\tEmptyToStringError: %q,\n", c.EmptyToStringError)
		} else {
			fmt.Fprintf(&b, "\t\tEmptyToString: %q,\n", c.EmptyToString)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("generated source does not parse: %v", err)
	}
	if _, err := os.Stdout.Write(src); err != nil {
		log.Fatal(err)
	}
}
